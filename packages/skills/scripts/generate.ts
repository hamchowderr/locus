/**
 * Generates the skill catalog from the docs snapshot in `source/`.
 *
 *   node scripts/generate.ts           write catalog/ and src/generated/
 *   node scripts/generate.ts --check   exit 1 if anything on disk is out of date
 *
 * Per GHL service it writes `catalog/<service>/manifest.ts`, `operations.md` and
 * `reference.md` (all regenerated every run) and creates `SKILL.md` once — after that the
 * SKILL.md is hand-written and never touched again.
 */

import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import { type ParsedDocs, type ParsedService, parseDocs } from "../src/docs/parse.ts";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const SOURCE = join(ROOT, "source");
const CATALOG = join(ROOT, "catalog");
const GENERATED = join(ROOT, "src", "generated");
const HEADER = "GENERATED by packages/skills/scripts/generate.ts from source/ — do not edit.";

interface SourceMeta {
  url: string;
  fetchedAt: string;
  sha256: string;
}

const check = process.argv.includes("--check");
const meta = JSON.parse(readFileSync(join(SOURCE, "meta.json"), "utf8")) as SourceMeta;
const docs = parseDocs(readFileSync(join(SOURCE, "v3-llms-full.txt"), "utf8"));

/** Files regenerated on every run, keyed by absolute path. */
const files = new Map<string, string>();
/** Files created only when missing. */
const seeds = new Map<string, string>();

for (const service of docs.services) {
  const dir = join(CATALOG, service.name);
  files.set(join(dir, "manifest.ts"), manifestFile(service, docs));
  files.set(join(dir, "operations.md"), operationsFile(service));
  files.set(join(dir, "reference.md"), `<!-- ${HEADER} -->\n\n${service.reference}`);
  seeds.set(join(dir, "SKILL.md"), skillStub(service));
}
files.set(join(GENERATED, "catalog.ts"), catalogFile(docs, meta));
files.set(join(SOURCE, "docs-defects.md"), defectsFile(docs));

const stale = staleServices(docs);
if (check) {
  const problems = [
    ...[...files].filter(([path, body]) => read(path) !== body).map(([path]) => path),
    ...[...seeds.keys()].filter((path) => !existsSync(path)),
    ...stale,
  ];
  if (problems.length > 0) {
    console.error(problems.map((p) => relative(ROOT, p)).join("\n"));
    console.error(
      "\nOut of date. Run `pnpm --filter @locus/skills generate` and commit the result.",
    );
    process.exit(1);
  }
  console.log(`catalog is up to date: ${docs.services.length} services, ${count(docs)} operations`);
} else {
  for (const [path, body] of files) write(path, body);
  for (const [path, body] of seeds) if (!existsSync(path)) write(path, body);
  console.log(`generated ${docs.services.length} services, ${count(docs)} operations`);
  if (docs.warnings.length > 0) {
    console.log(`${docs.warnings.length} docs defects recorded in source/docs-defects.md`);
  }
  for (const dir of stale) console.warn(`not in GHL's docs any more, review and delete: ${dir}`);
}

function manifestFile(service: ParsedService, docs: ParsedDocs): string {
  const manifest = {
    category: service.name,
    label: service.label,
    docsVersion: docs.version,
    operations: service.operations.map(({ sessionParams, body, ...op }) => ({
      ...op,
      ...(sessionParams.length > 0 ? { sessionParams } : {}),
      ...(body ? { body } : {}),
    })),
  };
  return [
    `// ${HEADER}`,
    'import type { SkillManifest } from "../../src/index.ts";',
    "",
    `export default ${JSON.stringify(manifest, null, 2)} as const satisfies SkillManifest;`,
    "",
  ].join("\n");
}

function operationsFile(service: ParsedService): string {
  const lines = [
    `<!-- ${HEADER} -->`,
    "",
    `# ${service.label} — operations`,
    "",
    `${service.operations.length} operations. Full request and response shapes: [reference.md](reference.md).`,
    "",
  ];
  for (const op of service.operations) {
    const flags = [
      op.method === "GET" ? "read" : "write",
      op.tokens.length === 0 ? "no auth" : op.tokens.join("/"),
      ...(op.body && op.body !== "json" ? [op.body] : []),
      ...(op.deprecated ? ["deprecated"] : []),
    ];
    lines.push(
      `- \`${op.id}\` — **${op.title}** — \`${op.method} ${op.path}\` (${flags.join(", ")})`,
      ...(op.summary ? [`  ${op.summary}`] : []),
    );
  }
  return `${lines.join("\n")}\n`;
}

function skillStub(service: ParsedService): string {
  return [
    "---",
    `name: ${service.name}`,
    `description: GoHighLevel ${service.label} — ${service.operations.length} operations.`,
    "---",
    "",
    `# ${service.label}`,
    "",
    "Hand-written guidance for this domain belongs here: which operation to use for which job,",
    "quirks the docs do not mention, which filters GHL applies natively and which it does not,",
    "and how this domain connects to others. Not written yet.",
    "",
    "- Operation index: [operations.md](operations.md) (generated)",
    "- Full reference: [reference.md](reference.md) (generated, verbatim from GHL's docs)",
    "",
  ].join("\n");
}

function catalogFile(docs: ParsedDocs, meta: SourceMeta): string {
  const ident = (name: string) => name.replace(/-(\w)/g, (_, c: string) => c.toUpperCase());
  return [
    `// ${HEADER}`,
    'import type { SkillManifest } from "../index.ts";',
    ...docs.services.map(
      (s) => `import ${ident(s.name)} from "../../catalog/${s.name}/manifest.ts";`,
    ),
    "",
    `export const docsSource = ${JSON.stringify({ ...meta, version: docs.version })} as const;`,
    "",
    "export const catalog: readonly SkillManifest[] = [",
    ...docs.services.map((s) => `  ${ident(s.name)},`),
    "];",
    "",
  ].join("\n");
}

function defectsFile(docs: ParsedDocs): string {
  return [
    `<!-- ${HEADER} -->`,
    "",
    "# Defects in GHL's docs",
    "",
    "Found while generating the catalog. None stops generation; each is worth knowing when an",
    "operation misbehaves.",
    "",
    ...(docs.warnings.length > 0 ? docs.warnings.map((w) => `- ${w}`) : ["None."]),
    "",
  ].join("\n");
}

function staleServices(docs: ParsedDocs): string[] {
  if (!existsSync(CATALOG)) return [];
  const current = new Set(docs.services.map((s) => s.name));
  return readdirSync(CATALOG, { withFileTypes: true })
    .filter((entry) => entry.isDirectory() && !current.has(entry.name))
    .map((entry) => join(CATALOG, entry.name));
}

function count(docs: ParsedDocs): number {
  return docs.services.reduce((n, s) => n + s.operations.length, 0);
}

function read(path: string): string | undefined {
  return existsSync(path) ? readFileSync(path, "utf8") : undefined;
}

function write(path: string, body: string): void {
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, body);
}
