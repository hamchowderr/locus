import { readdir, readFile } from "node:fs/promises";
import { join, relative, sep } from "node:path";

/** Where the vendored and Locus-written skills live, one directory per skill. */
export const SKILLS_DIR = new URL("../../skills/", import.meta.url);

/** Licence and notice files stay in the repository with their skill but are not served. */
const NOT_SERVED = /^(LICENSE|NOTICE)(\.[a-z]+)?$/i;

/** Every served text file of every skill: { skill: { "SKILL.md": "...", "rules/x.md": "..." } }. */
export async function readSkillFiles(
  dir: string = SKILLS_DIR.pathname,
): Promise<Record<string, Record<string, string>>> {
  const skills: Record<string, Record<string, string>> = {};
  const entries = await readdir(dir, { withFileTypes: true });
  for (const entry of entries.filter((e) => e.isDirectory()).sort(byName)) {
    const root = join(dir, entry.name);
    const files: Record<string, string> = {};
    for (const path of (await walk(root)).sort()) {
      const rel = relative(root, path).split(sep).join("/");
      if (!rel.endsWith(".md") || NOT_SERVED.test(rel)) continue;
      files[rel] = await readFile(path, "utf8");
    }
    skills[entry.name] = files;
  }
  return skills;
}

const byName = (a: { name: string }, b: { name: string }) => a.name.localeCompare(b.name);

async function walk(dir: string): Promise<string[]> {
  const out: string[] = [];
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) out.push(...(await walk(path)));
    else if (entry.isFile()) out.push(path);
  }
  return out;
}

/** The generated module's source for a set of skill files. */
export function bundleSource(skills: Record<string, Record<string, string>>): string {
  return `// Generated by scripts/bundle-skills.ts from packages/builder/skills. Do not edit: change the
// skill's files and run \`pnpm --filter @locus/builder skills:bundle\`.

export const SKILL_FILES: Record<string, Record<string, string>> = ${JSON.stringify(skills, null, 1)};
`;
}
