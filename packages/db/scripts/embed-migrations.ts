// Writes the tenant migrations into src/generated/tenant-migrations.ts.
//   node packages/db/scripts/embed-migrations.ts
// Tenant databases are migrated at run time, inside the deployed app, where the migrations
// folder doesn't exist: the bundler ships code, not this package's files. A test fails when
// the embedded copy and the folder disagree.
import { writeFile } from "node:fs/promises";
import { loadTenantMigrations } from "../src/tenant-migrations.ts";

const out = new URL("../src/generated/tenant-migrations.ts", import.meta.url);
const migrations = loadTenantMigrations();
await writeFile(
  out,
  `// Generated by scripts/embed-migrations.ts from migrations/tenant. Do not edit.
export const EMBEDDED_TENANT_MIGRATIONS: { hash: string; sql: string[] }[] = ${JSON.stringify(migrations, null, 2)};
`,
);
console.log(`embedded ${migrations.length} tenant migration(s)`);
